#!/usr/bin/env python3
"""Generate original, deterministic test examples; never fetch research data."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOPICS = ['轨迹交通', '城市计算', 'GeoAI 空间智能', '遥感多模态']
PARAGRAPH = ('这是一段为界面测试编写的合成文字，不对应真实论文或研究结论。'
             '示例按时间整理数据，比较不同分组，并观察表述在墨水屏上的换行效果。'
             '中文、English、数字 123 和标点共同用于检查字形、行距与跨页连续性。')


def paper(index):
    title = f'{TOPICS[index % len(TOPICS)]}：合成研究示例 {index + 1:02d}'
    # A bibliographic-only item exercises the missing-abstract fallback.
    summary = 'Volume 1, Issue 1, October 2026.' if index == 0 else PARAGRAPH
    if index == 2:
        summary = PARAGRAPH * 12  # Keep a long body to exercise reader pagination.
    return {
        'id': f'synthetic-paper-{index + 1:02d}', 'title': title,
        'translated_title': title, 'summary': summary, 'translated_summary': None,
        'source_name': 'Synthetic fixture / 合成示例',
        'source_url': f'https://example.org/papers/synthetic-{index + 1:02d}',
        'published_at': '2026-10-20T00:00:00+00:00',
        'created_at': '2026-10-24T08:00:00+00:00',
        'updated_at': '2026-10-24T09:00:00+00:00',
        'content_type': 'paper', 'topic_tags': [TOPICS[index % len(TOPICS)]],
    }


def dashboard(extended=False):
    items = [paper(i) for i in range(30 if extended else 6)]
    card = {
        'date_key': '2026-10-24', 'card_key': 'overview',
        'title': '合成科研简报：城市、轨迹与空间智能',
        'summary': '此处展示人工编写的接口示例，用于测试简报排版、日期与来源关联，不代表真实科研动态。',
        'highlights': ['检验中文与英文排版。', '保留发布时间与收录时间的区别。'],
        'item_ids': [items[0]['id'], items[1]['id']],
        'updated_at': '2026-10-24T08:30:00+00:00',
    }
    radars = [{
        'date_key': '2026-10-24', 'direction_key': f'synthetic-direction-{i}',
        'direction_title': title, 'trend_summary': PARAGRAPH,
        'trend_signals': ['这是合成信号，仅用于详情页测试。'],
        'core_viewpoints': ['这是合成观点，不应当作真实研究结论引用。'],
        'item_ids': [items[i]['id']], 'updated_at': '2026-10-24T09:15:00+00:00',
    } for i, title in enumerate(['轨迹与城市交通 · 示例', '多源地理数据 · 示例'])]
    result = {
        '_fixture': 'synthetic; generated by fixtures/generate.py; not live research',
        'version': 'synthetic-with-interests-v1' if extended else 'synthetic-dashboard-v1',
        'published_at': '2026-10-24T10:00:00+00:00', 'unavailable': [],
        'home': {'daily_summary': {'cards': [card]}, 'research_ideas': {'cards': []}},
        'digest': {'cards': radars}, 'papers': {'items': items[:6]},
    }
    if extended:
        # Include a duplicate and a non-paper; the adapter must filter them.
        result['latest'] = {'items': [items[0], *items[6:], {
            **paper(30), 'content_type': 'news', 'title': '合成资讯，不进入论文池',
        }]}
    return result


def main():
    for name, data in (
        ('synthetic-dashboard.json', dashboard()),
        ('synthetic-dashboard-with-interests.json', dashboard(True)),
    ):
        (HERE / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
